import { bumpMinorVersion, PolicyStore } from './policy-store.js';
import {
  DefensePolicyParameters,
  OptimizationProposal
} from './types.js';

export interface ObservedIncidentMetrics {
  meanMTTC: number; // ticks
  meanResilience: number; // 0 to 100
  containmentFailureRate?: number; // 0 to 1
  overSeveranceRate?: number; // 0 to 1
}

/**
 * Controlled Self-Improvement Optimizer.
 * Analyzes empirical operational metrics and synthesizes optimized candidate defense policies.
 * Strictly constrained to declarative parameter tuning — NO arbitrary code execution or unverified self-modification.
 */
export class PolicyOptimizer {
  private policyStore: PolicyStore;

  constructor(policyStore: PolicyStore) {
    this.policyStore = policyStore;
  }

  public synthesizeOptimization(
    tenantId: string,
    sourcePolicyId: string,
    metrics: ObservedIncidentMetrics
  ): OptimizationProposal {
    const sourcePolicy = this.policyStore.getPolicy(tenantId, sourcePolicyId);
    if (!sourcePolicy) {
      throw new Error(`Source policy not found: ${sourcePolicyId}`);
    }

    const currentParams = sourcePolicy.parameters;
    const suggestedParams: DefensePolicyParameters = { ...currentParams };
    const rationale: string[] = [];
    let expectedResilienceGain = 0;

    // Rule 1: High MTTC (> 3 ticks) indicates containment response is too slow or conservative
    if (metrics.meanMTTC > 3) {
      if (currentParams.isolationStrategy !== 'AGGRESSIVE_ISOLATE') {
        suggestedParams.isolationStrategy = 'AGGRESSIVE_ISOLATE';
        rationale.push(
          `Upgraded isolationStrategy to AGGRESSIVE_ISOLATE because observed MTTC (${metrics.meanMTTC.toFixed(1)} ticks) exceeded 3-tick SLO.`
        );
        expectedResilienceGain += 10;
      }
      if (suggestedParams.maxAutonomousSeverances < 3) {
        suggestedParams.maxAutonomousSeverances = 3;
        rationale.push(
          `Increased maxAutonomousSeverances to 3 to expedite lateral path severance.`
        );
      }
    }

    // Rule 2: Low resilience (< 70) with high severance indicates over-containment
    if (metrics.meanResilience < 70 && (metrics.overSeveranceRate ?? 0) > 0.15) {
      if (currentParams.containmentThreshold === 'LOW') {
        suggestedParams.containmentThreshold = 'MEDIUM';
        rationale.push(
          `Raised containmentThreshold from LOW to MEDIUM to reduce unnecessary disruption to operational workloads.`
        );
        expectedResilienceGain += 8;
      }
    }

    // Rule 3: High containment failure rate (> 10%)
    if ((metrics.containmentFailureRate ?? 0) > 0.1) {
      suggestedParams.confidenceThreshold = Math.max(
        0.5,
        currentParams.confidenceThreshold - 0.15
      );
      rationale.push(
        `Lowered confidenceThreshold to ${suggestedParams.confidenceThreshold.toFixed(2)} to accelerate automated response execution.`
      );
      expectedResilienceGain += 12;
    }

    // If no adjustments were needed, add default parameter tuning
    if (rationale.length === 0) {
      suggestedParams.maxAutonomousSeverances = Math.min(
        5,
        currentParams.maxAutonomousSeverances + 1
      );
      rationale.push('Optimized perimeter link severance capacity.');
      expectedResilienceGain = 5;
    }

    const suggestedVersion = bumpMinorVersion(sourcePolicy.version);
    const changelog = `Self-improvement optimization synthesized from empirical metrics:\n- ${rationale.join('\n- ')}`;

    // Create candidate draft in store (NOT active yet — must pass benchmark gates!)
    const candidateDraft = this.policyStore.createPolicy({
      tenantId,
      name: `${sourcePolicy.name} (Optimized)`,
      description: `Candidate policy generated by controlled self-improvement engine.`,
      version: suggestedVersion,
      status: 'CANDIDATE',
      parameters: suggestedParams,
      changelog
    });

    return {
      sourcePolicyId,
      suggestedVersion,
      suggestedParameters: suggestedParams,
      rationale,
      expectedResilienceGain,
      candidateDraft
    };
  }
}
